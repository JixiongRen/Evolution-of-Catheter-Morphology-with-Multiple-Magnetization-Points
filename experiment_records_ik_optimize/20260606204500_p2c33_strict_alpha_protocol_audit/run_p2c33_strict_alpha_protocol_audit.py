"""Audit requirements for a same-protocol alpha sensitivity scan."""

from __future__ import annotations

import csv
import json
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[2]
OUT_DIR = Path(__file__).resolve().parent
P2C22 = ROOT / "experiment_records_ik_optimize" / "20260606152302_p2c22_cross_condition_reliability_pilot"
P2C16 = ROOT / "experiment_records_ik_optimize" / "20260605132600_p2c16_alpha_boundary_phase_map"
P2C30 = ROOT / "experiment_records_ik_optimize" / "20260606194500_p2c30_rand20_multi_eps_recheck"
P2C31 = ROOT / "experiment_records_ik_optimize" / "20260606201000_p2c31_rand20_eps_boundary_refine"


def _jsonable(value: Any) -> Any:
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, dict):
        return {str(k): _jsonable(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [_jsonable(v) for v in value]
    return value


def _write_csv(path: Path, rows: list[dict[str, Any]]) -> None:
    fields = sorted({key for row in rows for key in row})
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fields)
        writer.writeheader()
        for row in rows:
            writer.writerow({field: row.get(field) for field in fields})


def _p2c22_state_exists(alpha: float) -> bool:
    return (P2C22 / f"n3_mixed_rand20_alpha_{alpha:.2f}_position_linearity.npz").exists()


def main() -> None:
    candidate_alphas = [0.375, 0.4, 0.425, 0.45]
    candidate_eps = [0.005, 0.01, 0.0125]
    alpha_rows: list[dict[str, Any]] = []
    for alpha in candidate_alphas:
        alpha_rows.append(
            {
                "alpha": alpha,
                "p2c22_saved_target_seed_exists": _p2c22_state_exists(alpha),
                "can_use_p2c30_directly": _p2c22_state_exists(alpha),
                "needs_target_seed_generation": not _p2c22_state_exists(alpha),
                "recommended_source": "P2c22 saved state" if _p2c22_state_exists(alpha) else "new target/seed generated by the P2c10w/P2c16 path",
            }
        )
    experiment_rows = [
        {
            "alpha": alpha,
            "eps_alpha": eps,
            "required_before_publish": "same target convention, same seed policy, strict multi-strategy refinement, re-optimized perturbation solves",
            "expected_role": "trusted-window replication" if alpha in (0.4, 0.425) and eps <= 0.01 else "failure-boundary diagnosis",
        }
        for alpha in candidate_alphas
        for eps in candidate_eps
    ]
    blockers = [
        {
            "blocker": "P2c30/P2c31 direct loader only has n3_mixed_rand20 alpha=0.40 in P2c22",
            "impact": "alpha sweep would silently mix target definitions if run without generating missing target/seed states",
            "resolution": "generate and save canonical target_p and best_y for every alpha before strict sensitivity replay",
        },
        {
            "blocker": "P2c16 and P2c30/P2c31 use different solver refinement policies",
            "impact": "trusted alpha window and eps boundary are currently comparable as evidence, but not a same-protocol statistical map",
            "resolution": "reuse P2c27/P2c29 strict multi-strategy refinement inside the arbitrary-alpha target path",
        },
        {
            "blocker": "P2c16 alpha=0.45 is continuation-dependent",
            "impact": "it cannot be published as a high-confidence sensitivity point until independent seeds reproduce the same branch",
            "resolution": "run independent-seed, continuation-seed, and reverse-continuation checks at alpha=0.45",
        },
    ]
    _write_csv(OUT_DIR / "alpha_state_availability.csv", alpha_rows)
    _write_csv(OUT_DIR / "recommended_strict_alpha_eps_grid.csv", experiment_rows)
    with (OUT_DIR / "failure_events.jsonl").open("w", encoding="utf-8") as f:
        for row in blockers:
            f.write(json.dumps(_jsonable(row), ensure_ascii=False) + "\n")
    summary = {
        "experiment": OUT_DIR.name,
        "source_evidence": [P2C16, P2C30, P2C31],
        "candidate_alphas": candidate_alphas,
        "candidate_eps": candidate_eps,
        "p2c22_available_alpha_count": sum(row["p2c22_saved_target_seed_exists"] for row in alpha_rows),
        "p2c22_missing_alpha_count": sum(not row["p2c22_saved_target_seed_exists"] for row in alpha_rows),
        "direct_p2c30_alpha_sweep_is_valid": False,
        "reason": "Only alpha=0.40 has the saved target/seed state required by the current P2c30/P2c31 loader.",
        "next_required_implementation": [
            "Add a canonical arbitrary-alpha target/seed generation stage.",
            "Inject P2c27/P2c29 strict multi-strategy refinement into the arbitrary-alpha path.",
            "Run alpha={0.375,0.400,0.425,0.450}, eps={0.005,0.010,0.0125} with re-optimized perturbation solves.",
        ],
    }
    (OUT_DIR / "summary.json").write_text(json.dumps(_jsonable(summary), ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps(_jsonable(summary), ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
